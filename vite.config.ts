/// <reference types="vitest" />
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

/**
 * Emits `sw.js`, a small service worker that makes the game installable and playable offline.
 * It is generated at build time so it lists exactly the files this build produced (their
 * names carry content hashes), and its cache name changes whenever any of them changes.
 *
 * Strategy: precache the whole app on install; serve assets cache-first; serve page loads
 * network-first with the cached page as the offline fallback, so an online player always
 * gets the newest build.
 */
const serviceWorker = (): Plugin => ({
  name: 'ofc-service-worker',
  apply: 'build',
  enforce: 'post',
  generateBundle(_options, bundle) {
    const publicDir = resolve(__dirname, 'public');
    const publicFiles = readdirSync(publicDir);
    const built = Object.keys(bundle).filter((file) => !file.endsWith('.map'));
    const files = [...new Set(['index.html', ...built, ...publicFiles])].sort();

    const hash = createHash('sha256');
    for (const file of files) hash.update(file);
    for (const file of publicFiles) hash.update(readFileSync(resolve(publicDir, file)));
    const index = bundle['index.html'];
    if (index && index.type === 'asset') hash.update(String(index.source));
    const version = hash.digest('hex').slice(0, 12);

    const assets = ['./', ...files.map((file) => `./${file}`)];
    this.emitFile({
      type: 'asset',
      fileName: 'sw.js',
      source: `// Generated by vite.config.ts. Do not edit.
const CACHE = 'ofc-poker-${version}';
const ASSETS = ${JSON.stringify(assets, null, 2)};
// Vite's script and style tags are "crossorigin", so their requests carry an Origin header
// that the precache requests do not. A server that answers "Vary: Origin" would then make
// every cached file a miss (a blank page offline). These are static, content-hashed files,
// so Vary is irrelevant to them.
const MATCH = { ignoreVary: true };

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key.startsWith('ofc-poker-') && key !== CACHE).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (new URL(request.url).origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // Page loads: newest version when online, the cached page when not.
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put('./index.html', copy));
          return response;
        })
        .catch(() => caches.match('./index.html', MATCH)),
    );
    return;
  }

  // Everything else is content-hashed or static: cache first.
  event.respondWith(
    caches.match(request, MATCH).then(
      (hit) =>
        hit ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`,
    });
  },
});

export default defineConfig({
  plugins: [react(), tailwindcss(), serviceWorker()],
  test: {
    environment: 'node',
    include: ['tests/**/*.test.ts'],
  },
});
